static const uint8_t _G_PLUS[7]    = {0,0x04,0x04,0x1F,0x04,0x04,0};
static const uint8_t _G_APOS[7]    = {0x04,0x04,0x08,0,0,0,0};
static const uint8_t _G_STAR[7]    = {0,0x15,0x0E,0x1F,0x0E,0x15,0};

static inline const uint8_t* glyph7(char c) {
  if (c >= '0' && c <= '9') return FONT_DIGIT[c - '0'];
  if (c >= 'A' && c <= 'Z') return FONT_UPPER[c - 'A'];
  if (c >= 'a' && c <= 'z') return FONT_UPPER[c - 'a'];
  switch (c) {
    case '.': return _G_DOT;   case ',': return _G_COMMA; case ':': return _G_COLON;
    case '-': return _G_MINUS; case '>': return _G_GT;    case '<': return _G_LT;
    case '%': return _G_PCT;   case '(': return _G_LP;    case ')': return _G_RP;
    case '&': return _G_AMP;   case '/': return _G_SLASH; case '!': return _G_EXCL;
    case '?': return _G_QUES;  case '+': return _G_PLUS;  case '\'': return _G_APOS;
    case '*': return _G_STAR;
    default:  return _G_SPACE;
  }
}
