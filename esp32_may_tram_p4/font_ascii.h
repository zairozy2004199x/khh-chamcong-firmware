static const uint8_t GLYPH_DD[7]   = {0x03,0x0F,0x0F,0x11,0x11,0x11,0x0F}; // đ
static const uint8_t _G_SPACE[7]   = {0,0,0,0,0,0,0};
static const uint8_t _G_DOT[7]     = {0,0,0,0,0,0x06,0x06};
static const uint8_t _G_COMMA[7]   = {0,0,0,0,0,0x06,0x08};
